"""Generate the opengl32.dll export plumbing from the system opengl32.dll.

Outputs (src/gen/), per architecture (x64 from System32, x86 from SysWOW64):
  opengl32_<arch>.def                every system export, same ordinals; implemented ones map to H_<name>
  forward_x64.asm / forward_x86.cpp  jump stubs for everything not implemented in C++
  forward_names_<arch>.inc           C string table, index == stub index

Implemented exports are listed in src/exports_impl.txt (one name per line).
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def pe_exports(path):
    data = open(path, 'rb').read()
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    magic = struct.unpack_from('<H', data, pe + 24)[0]
    dd = pe + 24 + (112 if magic == 0x20B else 96)
    exp_rva = struct.unpack_from('<I', data, dd)[0]
    nsec = struct.unpack_from('<H', data, pe + 6)[0]
    opt_size = struct.unpack_from('<H', data, pe + 20)[0]
    sec = pe + 24 + opt_size
    sections = [struct.unpack_from('<8sIIII', data, sec + i * 40) for i in range(nsec)]

    def off(rva):
        for _, vsize, va, rsize, raw in sections:
            if va <= rva < va + max(vsize, rsize):
                return rva - va + raw
        raise ValueError(hex(rva))

    e = off(exp_rva)
    base, nfunc, nnames, afuncs, anames, aords = struct.unpack_from('<IIIIII', data, e + 16)
    out = []
    for i in range(nnames):
        name_rva = struct.unpack_from('<I', data, off(anames) + i * 4)[0]
        o = off(name_rva)
        name = data[o:data.index(b'\0', o)].decode()
        ordinal = struct.unpack_from('<H', data, off(aords) + i * 2)[0] + base
        out.append((ordinal, name))
    return sorted(out)


# x64: the cached target is used directly; the first call saves the argument registers around
# S3D_ResolveForward (keeps rsp 16-aligned at the call).
ASM_X64_MACRO = r"""FWD MACRO name, idx
    LOCAL slow, fail
name PROC
    mov rax, qword ptr [g_s3dForward + idx*8]
    test rax, rax
    jz slow
    jmp rax
slow:
    push rcx
    push rdx
    push r8
    push r9
    sub rsp, 68h
    movdqu [rsp+20h], xmm0
    movdqu [rsp+30h], xmm1
    movdqu [rsp+40h], xmm2
    movdqu [rsp+50h], xmm3
    mov ecx, idx
    call S3D_ResolveForward
    movdqu xmm0, [rsp+20h]
    movdqu xmm1, [rsp+30h]
    movdqu xmm2, [rsp+40h]
    movdqu xmm3, [rsp+50h]
    add rsp, 68h
    pop r9
    pop r8
    pop rdx
    pop rcx
    test rax, rax
    jz fail
    jmp rax
fail:
    xor eax, eax
    ret
name ENDP
ENDM
"""

# x86: every opengl32 export is __stdcall with stack arguments, so a stub only touches eax/ecx/edx
# (caller-saved) and jumps to the target with the caller's stack untouched.
CPP_X86_MACRO = r"""#define S3D_FWD(name, idx)                                     \
    extern "C" __declspec(naked) void name()                   \
    {                                                          \
        __asm { mov eax, dword ptr g_s3dForward[idx * 4] }     \
        __asm { test eax, eax }                                \
        __asm { jz slow }                                      \
        __asm { jmp eax }                                      \
        __asm { slow: push idx }                               \
        __asm { call S3D_ResolveForward }                      \
        __asm { add esp, 4 }                                   \
        __asm { test eax, eax }                                \
        __asm { jz fail }                                      \
        __asm { jmp eax }                                      \
        __asm { fail: xor eax, eax }                           \
        __asm { ret }                                          \
    }
"""


def generate(arch, sysdll, impl, gen):
    exports = pe_exports(sysdll)
    names = {n for _, n in exports}
    missing = [n for n in impl if n not in names]
    if missing:
        sys.exit(f'{sysdll}: exports_impl.txt names not exported: ' + ', '.join(missing))
    fwd = [n for _, n in exports if n not in impl]

    with open(os.path.join(gen, f'opengl32_{arch}.def'), 'w', newline='\r\n') as f:
        f.write(f'; generated by tools/gen_exports.py from {sysdll} - do not edit\n')
        f.write('LIBRARY opengl32\nEXPORTS\n')
        for ordinal, n in exports:
            target = f'{n} = H_{n}' if n in impl else n
            f.write(f'    {target} @{ordinal}\n')

    if arch == 'x64':
        with open(os.path.join(gen, 'forward_x64.asm'), 'w', newline='\r\n') as f:
            f.write('; generated by tools/gen_exports.py - do not edit\n')
            f.write('EXTERN S3D_ResolveForward:PROC\nEXTERN g_s3dForward:QWORD\n\n')
            f.write(ASM_X64_MACRO + '\n.code\n')
            for i, n in enumerate(fwd):
                f.write(f'FWD {n}, {i}\n')
            f.write('END\n')
    else:
        with open(os.path.join(gen, 'forward_x86.cpp'), 'w', newline='\r\n') as f:
            f.write('// generated by tools/gen_exports.py - do not edit\n#if defined(_M_IX86)\n')
            f.write(f'extern "C" void* g_s3dForward[{len(fwd)}];\n')
            f.write('extern "C" void* __cdecl S3D_ResolveForward(unsigned idx);\n\n')
            f.write(CPP_X86_MACRO + '\n')
            for i, n in enumerate(fwd):
                f.write(f'S3D_FWD({n}, {i})\n')
            f.write('#endif\n')

    with open(os.path.join(gen, f'forward_names_{arch}.inc'), 'w', newline='\r\n') as f:
        f.write('// generated by tools/gen_exports.py - do not edit\n')
        f.write(f'#define S3D_FORWARD_COUNT {len(fwd)}\n')
        f.write('static const char* const kForwardNames[S3D_FORWARD_COUNT] = {\n')
        for n in fwd:
            f.write(f'    "{n}",\n')
        f.write('};\n')
    print(f'{arch}: {len(exports)} exports, {len(impl)} implemented, {len(fwd)} forwarded')


def main():
    windir = os.environ.get('SystemRoot', r'C:\Windows')
    impl_path = os.path.join(ROOT, 'src', 'exports_impl.txt')
    impl = [l.strip() for l in open(impl_path) if l.strip() and not l.startswith('#')]
    gen = os.path.join(ROOT, 'src', 'gen')
    os.makedirs(gen, exist_ok=True)
    generate('x64', os.path.join(windir, 'System32', 'opengl32.dll'), impl, gen)
    generate('x86', os.path.join(windir, 'SysWOW64', 'opengl32.dll'), impl, gen)


if __name__ == '__main__':
    main()
